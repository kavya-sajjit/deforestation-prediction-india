"""Collect every run into the tables and figures the README shows.

    python -m deforest.summarize results

Writes results/SUMMARY.md, results/<task>_<scheme>.csv, and PR-curve figures.
All numbers in the README must come from this file.
"""
from __future__ import annotations

import glob
import json
import os
import sys

import numpy as np
import pandas as pd

from .metrics import block_bootstrap, point_metrics

COLS = ["ap", "roc_auc", "f1", "precision", "recall", "balanced_acc", "mcc", "capture_top10"]
NICE = {"ap": "AP (PR-AUC)", "roc_auc": "ROC-AUC", "f1": "F1", "precision": "Precision",
        "recall": "Recall", "balanced_acc": "Bal. acc.", "mcc": "MCC", "capture_top10": "Loss in top-10% risk"}


def _fmt(m, s):
    return "–" if np.isnan(m) else f"{m:.3f} ± {s:.3f}"


def summarize(root: str = "results") -> str:
    lines = ["# Results (auto-generated by `python -m deforest.summarize`)\n"]
    for task_dir in sorted(glob.glob(os.path.join(root, "*", "*"))):
        task, scheme = task_dir.split(os.sep)[-2:]
        rows, pooled = [], []
        for exp_dir in sorted(glob.glob(os.path.join(task_dir, "*"))):
            name = os.path.basename(exp_dir)
            per_split = []
            for mf in sorted(glob.glob(os.path.join(exp_dir, "*", "metrics.json"))):
                with open(mf) as fh:
                    m = json.load(fh)
                m["split"] = os.path.basename(os.path.dirname(mf))
                per_split.append(m)
                p = pd.read_csv(os.path.join(os.path.dirname(mf), "preds.csv"))
                p = p[p.split == "test"].assign(experiment=name, fold=m["split"])
                pooled.append(p)
            if not per_split:
                continue
            df = pd.DataFrame(per_split)
            row = dict(experiment=name, splits=len(df), test_patches=int(df.n.sum()),
                       test_positives=int(df.positives.sum()), chance_ap=float(df.pos_rate.mean()))
            for c in COLS:
                row[c] = float(df[c].mean()); row[c + "_sd"] = float(df[c].std(ddof=0))
            ex = []
            for ef in glob.glob(os.path.join(exp_dir, "*", "explanations.json")):
                with open(ef) as fh:
                    ex.append(json.load(fh))
            if ex:
                row["expl_lift"] = float(np.mean([e["lift_over_chance"] for e in ex]))
                row["expl_rand_rho"] = float(np.mean([e["spearman_vs_random_model"] for e in ex]))
                comp = [e.get("max_completeness_error") for e in ex if "max_completeness_error" in e]
                row["completeness_err"] = float(max(comp)) if comp else np.nan
            rows.append(row)
        if not rows:
            continue
        tab = pd.DataFrame(rows)
        allp = pd.concat(pooled, ignore_index=True)
        cis = {}
        for name, g in allp.groupby("experiment"):
            lo, hi = block_bootstrap(g.reset_index(drop=True), "ap", n_boot=500)
            cis[name] = f"[{lo:.3f}, {hi:.3f}]"
        tab["ap_95ci_block_bootstrap"] = tab.experiment.map(cis)
        tab.to_csv(os.path.join(root, f"{task}_{scheme}.csv"), index=False)

        lines.append(f"\n## {task} — {scheme} split\n")
        lines.append(f"Chance-level AP (= share of positive patches): {tab.chance_ap.mean():.3f}. "
                     f"Mean ± SD across {int(tab.splits.max())} spatial splits; 95% CI from a block bootstrap of pooled test predictions.\n")
        hdr = ["Experiment"] + [NICE[c] for c in COLS] + ["AP 95% CI"]
        lines.append("| " + " | ".join(hdr) + " |")
        lines.append("|" + "---|" * len(hdr))
        for _, r in tab.sort_values("ap", ascending=False).iterrows():
            vals = [_fmt(r[c], r[c + "_sd"]) for c in COLS]
            lines.append(f"| {r.experiment} | " + " | ".join(vals) + f" | {r.ap_95ci_block_bootstrap} |")
        if "expl_lift" in tab:
            lines.append("\n**Explanation checks** (positive test patches)\n")
            lines.append("| Experiment | Evidence on lost pixels ÷ chance | Spearman vs random-weight model (lower is better) | Max completeness error |")
            lines.append("|---|---|---|---|")
            for _, r in tab.dropna(subset=["expl_lift"]).iterrows():
                ce = "n/a (Grad-CAM)" if np.isnan(r.get("completeness_err", np.nan)) else f"{r.completeness_err:.1e}"
                lines.append(f"| {r.experiment} | {r.expl_lift:.2f}× | {r.expl_rand_rho:.2f} | {ce} |")
        abl = glob.glob(os.path.join(task_dir, "*", "*", "band_ablation.csv"))
        if abl:
            a = pd.concat([pd.read_csv(f).assign(experiment=f.split(os.sep)[-3]) for f in abl])
            piv = a.groupby(["experiment", "channel", "region"]).ap_drop.mean().unstack("region").round(3)
            lines.append("\n**Band ablation** — drop in AP when one input channel is replaced by its training mean\n")
            lines.append(piv.to_markdown())
        _pr_figure(allp, os.path.join(root, f"pr_{task}_{scheme}.png"), f"{task} ({scheme} split)")
        lines.append(f"\n![PR curves](pr_{task}_{scheme}.png)\n")
    text = "\n".join(lines)
    with open(os.path.join(root, "SUMMARY.md"), "w") as fh:
        fh.write(text)
    print(text)
    return text


def _pr_figure(allp: pd.DataFrame, path: str, title: str):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from sklearn.metrics import precision_recall_curve
    fig, ax = plt.subplots(figsize=(5.5, 4.5))
    for name, g in allp.groupby("experiment"):
        if g.y.nunique() < 2:
            continue
        pr, rc, _ = precision_recall_curve(g.y, g.p)
        ap = point_metrics(g.y.to_numpy(), g.p.to_numpy(), 0.5)["ap"]
        ax.plot(rc, pr, label=f"{name} (AP {ap:.2f})", lw=1.4)
    ax.axhline(allp.y.mean(), ls="--", c="grey", lw=1, label=f"chance ({allp.y.mean():.2f})")
    ax.set_xlabel("Recall"); ax.set_ylabel("Precision"); ax.set_title(title)
    ax.legend(fontsize=7); fig.tight_layout(); fig.savefig(path, dpi=130); plt.close(fig)


if __name__ == "__main__":
    summarize(sys.argv[1] if len(sys.argv) > 1 else "results")
